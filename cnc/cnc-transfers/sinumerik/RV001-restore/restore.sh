#!/usr/bin/env bash
# Повна заливка РВ-001 (Sinumerik) після стирання ППЗУ.
# Лежить поруч із файлами; запускати звідси: ./restore.sh
#
#   ./restore.sh        обидва заходи, з паузою на оператора між ними
#   ./restore.sh 1      лише перший захід (TEA1)
#   ./restore.sh 2      лише другий захід (решта пʼяти)
#
#   --port /dev/ttyS0   назвати порт явно. Без нього порт шукається сам, і лише
#                       якщо він у системі один; кілька — інструмент відмовиться
#                       й перелічить їх.
#
# ДВА ЗАХОДИ, А НЕ ОДИН — ЧОМУ (знайдено 2026-08-06)
# Мануал, розд. 8: `MD 5`, `MD 8`, `MD 12` і `MD 20` **не активуються ні
# ребутом, ні Power On** — тільки софткнопками `FORMAT USER M.` +
# `CLEAR PART PR.`. Дослівно з розд. 5.1 (стор. 5–2):
#   "The user memory is reformatted, depending on NC MD 5 and 8. Any
#    modification to these two MD only takes effect after the FORMAT USER M.
#    and CLEAR PART PR. softkeys have been activated."
#
# Стара процедура тиснула форматування кроком 1, а TEA1 приходив кроком 6.
# Тобто памʼять щоразу розмічалась за чужими MD, а наші `MD 8 = 50` і `MD 20`
# не діяли ЖОДНОГО РАЗУ. Квитанція — аларм 31 при першій же спробі залити УП
# на порожню памʼять.
#
# Тепер: TEA1 їде першим заходом, оператор повторно форматує вже з ним, і
# аж тоді їде решта пʼяти. Перевірено двічі, цифри повторювані:
# `Freier Speicher` після другого форматування ≈ 88 972 (при `MD 20 = 32`).
#
# ЩО РОБИТЬ ОПЕРАТОР
# Тисне START на стійці перед кожним файлом. Між заходами — перезапуск стійки
# й повторний вхід у OVERALL RESET клавішею з оком.
#
# ЯК СКРИПТ ВИРІШУЄ, ЩО ПОРА СЛАТИ
# Гейт — перехід CTS 1->0->1: стійка спершу мусить вийти з попереднього
# прийому, і аж тоді знову ввійти. Це і є натиснутий START.
#
# Чому перехід, а не рівень: 2026-08-04 гейт по рівню (CTS=1) пропустив три
# файли підряд за 23 с без жодного старту — після TEA2 стійка лишила CTS
# піднятим. Перехід у такому разі просто стоїть і чекає, тобто помиляється
# в бік простою, а не в бік сміття в лінії. Не міняти на рівень.
#
# ЧОМУ ВСЕРЕДИНІ ЗАХОДУ — ОДИН ВИКЛИК НА ВСІ ФАЙЛИ
# Порт лишається відкритим наскрізь. Коли він закривався між файлами,
# на кожному стику був сліпий проміжок у кілька секунд; оператор тисне START
# одразу після кінця передачі, стійка встигала і відпустити, і знову підняти
# CTS у цю дірку, а наступний виклик потім вічно чекав падіння, якого вже
# не буде. Між ЗАХОДАМИ це не діє: там стійка перезавантажується.

set -u
SRC="$(cd "$(dirname "$0")" && pwd)"
# Інструмент передачі — рівно на рівень вище: ця папка лежить усередині
# каталогу sinumerik/. Шлях відносний навмисно, щоб каталог верстата можна було
# скопіювати на робоче місце цілим і нічого не правити. Абсолютного
# ~/cnc-transfers/... тут бути не повинно.
TOOL="$SRC/../sinumerik"

# Скільки терпіти START на кожному файлі.
GATE=3600
# Таймаут "лінія не бере байт". Довгий свідомо: стійка ділить великі файли на
# пакети й посеред передачі відпускає CTS, чекаючи нового старту. Ядро при
# цьому притримує байти й дошле решту само — рвати передачу через 30 с не можна.
# Мертву лінію видно з анімації: замість спінера "!" і лічильник СТОП m:ss.
STALL=1800

# Перший захід — тільки машинні дані ЧПК.
PASS1=(TEA1.NC)
# Другий — усе інше, у перевіреному порядку.
# PCA-en.nc замість PCA.nc: тексти алярмів PLC англійською, залито 2026-08-06.
# Це наш файл, не Siemens; оригінал німецькою лишається поруч як PCA.nc.
PASS2=(TEA2.NC PCP.NC PCA-en.nc LP.nc asm_dat.nc)

B=$'\033[1m'; Y=$'\033[33m'; R=$'\033[31m'; G=$'\033[32m'; N=$'\033[0m'

WHICH=0
PORT=""
while [ $# -gt 0 ]; do
    case "$1" in
        --port)   [ $# -ge 2 ] || { echo "--port потребує значення"; exit 2; }
                  PORT="$2"; shift 2 ;;
        --port=*) PORT="${1#--port=}"; shift ;;
        0|1|2)    WHICH="$1"; shift ;;
        *)        echo "usage: $0 [1|2] [--port /dev/ttyS0]"; exit 2 ;;
    esac
done

# Глобальні прапорці ядра мусять стояти ПЕРЕД словом `send`, інакше argparse
# їх не візьме.
PORTARG=()
[ -n "$PORT" ] && PORTARG=(--port "$PORT")

[ -x "$TOOL" ] || { echo "${R}нема інструмента: $TOOL${N}"; exit 1; }
for f in "${PASS1[@]}" "${PASS2[@]}"; do
    [ -f "$SRC/$f" ] || { echo "${R}нема файла: $SRC/$f${N}"; exit 1; }
done

send_pass() {                       # $1 = назва заходу, далі файли
    local title="$1"; shift
    local full=() f
    for f in "$@"; do full+=("$SRC/$f"); done
    echo "${B}${title}${N}   файли: $*"
    # --trim-tail: як цеховий CIMCO — відкинути хвіст-padding після завершального
    # M02/M17 і забезпечити CRLF у кінці файлу. Для TEA1/TEA2/asm_dat майже
    # порожня операція; для PCP/PCA/LP прибирає зайвий START і ручний STOP.
    "$TOOL" "${PORTARG[@]}" send --gate "$GATE" --wait 0 --stall "$STALL" \
        --trim-tail "${full[@]}"
}

between() {
    echo
    echo "${Y}${B}  ────────────  МЕЖДИННА СТЪПКА НА СТОЙКАТА  ────────────${N}"
    cat <<'EOF'

  1.  СЛОЖИ БАТЕРИЯТА  —  сега, преди изключване.
      Без нея машинните данни се губят при спиране на тока
      и целият пръв заход отива на вятъра.

  2.  Изключи стойката.

  3.  Задръж бутона с ОКОТО и включи стойката, без да го пускаш.
      Дръж го, докато на екрана се появи  OVERALL RESET.

  4.  НИЩО в менютата не се пипа.
      Рестартът след TEA1 сам форматира паметта, вече по нашите
      машинни данни; другите нулирания са направени в първия заход.

         бутон 2  [NC DATEN]      —  НЕ
         бутон 3  [PLC INITIAL]   —  НЕ
         бутон 4  [MASCH.-DATEN]  —  НЕ

      ⚠  Последният е и опасен: трие машинните данни заедно с
         битовете на опциите.

  5.  Провери на екрана:  Freier Speicher  ≈  88 972
      Ако е 28 360 или 0 — форматирането не е видяло нашите MD.
      Спри тук и не продължавай.

  6.  [DATEN EIN-AUS] (бутон 1) → сетинг данните:
         5011  ←  111          5012  ←  1
         5013  ←  111          5014  ←  10001
                               5015  ←  10010011
      → [DATEN-EINGABE] → Eingabeschnittstelle ← 1

EOF
    echo "${B}  Готово ли е?  Натисни ENTER, за да тръгнат останалите пет файла.${N}"
    read -r _
}

if [ "$WHICH" != 2 ]; then
    echo "${B}Заливка РВ-001 · заход 1 от 2${N}"
    echo "Тисни START на стійці. Ctrl-C зупиняє."
    echo
    send_pass "заход 1" "${PASS1[@]}" || {
        echo; echo "${R}перший захід обірвано${N}"; exit 1; }
    echo "${G}TEA1 віддано${N}"
fi

[ "$WHICH" = 0 ] && between

if [ "$WHICH" != 1 ]; then
    echo
    echo "${B}Заливка РВ-001 · заход 2 от 2${N}"
    echo "${Y}asm_dat.nc — найбільший, кілька хвилин. Це не зависання.${N}"
    echo
    send_pass "заход 2" "${PASS2[@]}" || {
        echo; echo "${R}послідовність обірвано — дивись, на якому файлі${N}"; exit 1; }
    echo
    echo "${B}усі шість віддано${N}"
    echo "далі: INBETRIEBN. ENDE (бутон 5), после — списъкът в instrukcia.txt"
fi
